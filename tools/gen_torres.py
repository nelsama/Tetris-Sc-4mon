# Formato 0xAABBGGRR. Las torres usan una paleta PROPIA (no la 3), con 3 colores
# en idx1/idx2/idx3 (libres). 0xffa60100 = AZUL (fondo) -> idx0 transparente.
COLOR_TO_IDX = {
    0x00000000: 0,
    0xffa60100: 0,   # AZUL (fondo) -> transparente
    0xff004de1: 1,   # marron claro
    0xff0084ff: 2,   # naranja claro
    0xff00bcff: 3,   # amarillo
}

def planos(frame):
    p0 = [0]*8; p1 = [0]*8
    for r in range(8):
        for c in range(8):
            idx = COLOR_TO_IDX[frame[r*8+c]]
            p0[r] |= (idx & 1) << (7-c)
            p1[r] |= ((idx >> 1) & 1) << (7-c)
    return p0, p1

def emit(name, frame):
    p0, p1 = planos(frame)
    print("static const uint8_t %s_p0[8] = { %s };" % (name, ", ".join("0x%02X" % x for x in p0)))
    print("static const uint8_t %s_p1[8] = { %s };" % (name, ", ".join("0x%02X" % x for x in p1)))

if __name__ == "__main__":
    for i, f in enumerate(frames):
        emit("torre%d" % (i + 1), f)
