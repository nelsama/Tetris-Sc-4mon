"""Renderiza el fondo del Tetris (cielo + torres) a una imagen PNG/ASCII,
usando exactamente los patrones y paletas del codigo C, para comparar con la foto.
Genera una imagen PPM y una version ASCII de colores dominantes.
"""
W_CELLS, H_CELLS = 40, 30

# --- Paletas reales de setup_video (RGB444 -> RGB888 aprox) ---
def rgb444(r,g,b):
    return (r*17, g*17, b*17)

PAL = {
 0: {0:None,                       1:rgb444(0x0,0xA,0xF), 2:rgb444(0x0,0x0,0xA), 3:rgb444(0x8,0x8,0x8)},
 1: {0:None,                       1:rgb444(0xF,0xE,0x0), 2:rgb444(0xF,0x8,0x0), 3:rgb444(0xF,0xF,0xF)},
 2: {0:None,                       1:rgb444(0x0,0xD,0x2), 2:rgb444(0xE,0x0,0x0), 3:rgb444(0xF,0x0,0xF)},
 3: {0:None,                       1:rgb444(0xC,0x5,0x0), 2:rgb444(0xF,0xC,0x1), 3:rgb444(0x8,0x3,0x0)},
}
BG_COLOR = rgb444(0x0,0x0,0x3)

# --- Patrones (p0,p1) por tile ---
TRI = {0:([0]*8,[0]*8)}  # blank
TRI[0x09] = ([0]*8,[0x00,0x80,0x00,0x80,0x00,0x40,0x20,0x00])  # sky1 pal3
TRI[0x0A] = ([0]*8,[0x00,0x12,0x00,0x00,0x00,0x00,0x40,0x00])  # sky2
TRI[0x0B] = ([0]*8,[0x02,0x00,0x80,0xC0,0x00,0x00,0x80,0x00])  # sky3
TRI[0x0C] = ([0]*8,[0x00,0x20,0x02,0x00,0x40,0x10,0x00,0x00])  # sky4
TORRES = {
 0x12:([0xFE,0xFC,0xF8,0xF8,0xFC,0xFE,0xFC,0xF8],[0x01,0x03,0x07,0x07,0x03,0x01,0x03,0x07]),
 0x13:([0xF0,0xE0,0xE0,0xF3,0xFF,0xFF,0xFF,0xFF],[0x0F,0x1F,0x1F,0x0C,0x00,0x00,0x00,0x00]),
 0x14:([0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xE7],[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x18]),
 0x15:([0xE0,0xF3,0xFF,0xFF,0xFF,0x8F,0xF0,0xFF],[0x1F,0x0C,0x00,0x00,0x00,0x70,0x0F,0x00]),
 0x16:([0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF],[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00]),
 0x17:([0xFF,0x7F,0x3F,0x3F,0x7F,0xFF,0x7F,0x3F],[0x00,0x80,0xC0,0xC0,0x80,0x00,0x80,0xC0]),
 0x18:([0x1F,0x0F,0x0F,0x9F,0xFF,0xFF,0xFF,0xFF],[0xE0,0xF0,0xF0,0x60,0x00,0x00,0x00,0x00]),
 0x19:([0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xCF],[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x30]),
 0x1A:([0x0F,0x9F,0xFF,0xFF,0xFF,0xE3,0x1F,0xFF],[0xF0,0x60,0x00,0x00,0x00,0x1C,0xE0,0x00]),
 0x1B:([0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF],[0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00]),
}
TILESTORE = dict(TRI); TILESTORE.update(TORRES)

# --- Grid de atributos (tile, pal) por celda ---
grid = [[(0x09, 3)] * W_CELLS for _ in range(H_CELLS)]

def draw_tower(col, alto):
    alto = max(5, min(10, alto))
    top = 30 - alto
    pisoL = [0x12,0x13,0x14,0x15,0x16]
    pisoR = [0x17,0x18,0x19,0x1A,0x1B]
    for i in range(5):
        if top+i < H_CELLS:
            grid[top+i][col] = (pisoL[i], 3)
            if col+1 < W_CELLS: grid[top+i][col+1] = (pisoR[i], 3)
    y = top+5
    while y <= 29:
        grid[y][col] = (0x16, 3)
        if col+1 < W_CELLS: grid[y][col+1] = (0x1B, 3)
        y += 1

towerL = [10, 6, 9, 5, 8, 7, 10]
towerR = [7, 9, 5, 10, 6, 8, 7]
for t in range(7):
    draw_tower(t*2, towerL[t])
    draw_tower(26+t*2, towerR[t])

# Cielo: variante por hash (identico a draw_background en C)
sky_tiles = [0x09, 0x0A, 0x0B, 0x0C]
for y in range(H_CELLS):
    for x in range(W_CELLS):
        if grid[y][x][1] == 3 and grid[y][x][0] == 0x09:
            h = ((x*5 + y*11) ^ (x*y)) & 0xFF
            grid[y][x] = (sky_tiles[h & 3], 3)

# --- Render a pixel: cada celda 8x8 ---
IMG_W, IMG_H = W_CELLS*8, H_CELLS*8
img = [[BG_COLOR]*IMG_W for _ in range(IMG_H)]
for cy in range(H_CELLS):
    for cx in range(W_CELLS):
        tile, pal = grid[cy][cx]
        p0, p1 = TILESTORE[tile]
        for r in range(8):
            for c in range(8):
                b = 7-c
                idx = ((p1[r]>>b)&1)<<1 | ((p0[r]>>b)&1)
                col = PAL[pal][idx] if idx != 0 else BG_COLOR
                img[cy*8+r][cx*8+c] = col

# Escribe PPM
with open("tools/ref_fondo.ppm","w") as f:
    f.write("P3\n%d %d\n255\n" % (IMG_W, IMG_H))
    for row in img:
        f.write(" ".join("%d %d %d"%px for px in row) + "\n")
print("Escrito tools/ref_fondo.ppm (%dx%d)." % (IMG_W, IMG_H))

# Resumen ASCII por color dominante
def name(px):
    return {(0,0,3*17):'bg', rgb444(0x0,0xA,0xF):'cian', rgb444(0x0,0x0,0xA):'azul',
            rgb444(0x8,0x8,0x8):'gris', rgb444(0xD,0x9,0x2):'NARANJA',
            rgb444(0x0,0x1,0x6):'azulO', rgb444(0x0,0x7,0xF):'azulC'}.get(px,'?')
print("\nVista por celda (color del pixel 0,0 de cada celda):")
for y in range(H_CELLS):
    print("".join(name(img[y*8][x*8])[:1] for x in range(W_CELLS)))
